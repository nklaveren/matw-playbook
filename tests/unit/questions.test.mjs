// The questionnaire content: 21 questions, their full statements, the
// category counts and the terms the AI answers have to keep.
import test from "node:test";
import assert from "node:assert/strict";
import { loadSource } from "../../scripts/lib/source.mjs";

const { questions, cats } = loadSource();

const EXPECTED_STATEMENTS = [
  "How do you handle concurrency in Go? How do you avoid goroutine leaks?",
  "How do you handle errors in Go, and how does that differ from exceptions?",
  "How would you design a POST endpoint so that sending the same request twice does not create duplicates?",
  "Offset pagination vs cursor (keyset) pagination: when would you use each?",
  "(Only if no production Go) What statically typed language do you use, and how would you ramp up on Go?",
  "A query on a table with 50 million rows became slow. Walk me through how you investigate it.",
  "Two requests try to update the same record at the same time. How do you prevent inconsistent data?",
  "How do you run a schema migration on a large table without downtime?",
  "How do you manage server data in a React app, for example a list that the user can edit?",
  "When would you deploy a service on Kubernetes and when would you use a managed AWS service like Lambda, ECS Fargate or SQS?",
  "What is the N+1 problem in GraphQL and how do you solve it?",
  "If a service publishes events to Kafka, how do you guarantee that the database and the event stay consistent?",
  "Which infrastructure have you managed with Terraform, and how do you handle state?",
  "How do you test a Go service that talks to PostgreSQL?",
  "You are on call at 2 a.m. and API latency jumps from 80 ms to 4 seconds. What do you do in the first 15 minutes?",
  "What do you monitor in a backend service?",
  "Walk me through the last feature you built using an AI coding assistant. What did you delegate and what did you do yourself?",
  "Tell me about a time you rejected or corrected code generated by AI. What was wrong?",
  "Have you built any feature using LLMs, for example with LangChain, LangGraph or a vector database?",
  "Tell me about a workstream you owned from design to production without supervision. How did you break it down and prioritize?",
  "Product asks you for a feature you think is a bad idea or is not well defined. What do you do?"
];

const EXPECTED_COUNTS = {
  go: 5,
  sql: 3,
  fe: 1,
  arc: 4,
  qa: 3,
  ai: 3,
  own: 2
};

const AI_TERMS = ["promptfoo", "golden dataset", "test oracle", "pgvector", "RAG"];

test("the questionnaire has exactly 21 questions", () => {
  assert.equal(questions.length, 21);
});

test("the question ids are 1..21, in order and unique", () => {
  const ids = questions.map((q) => q.id);
  assert.deepEqual(ids, Array.from({ length: 21 }, (_, i) => i + 1));
  assert.equal(new Set(ids).size, 21);
});

test("every statement is present and complete", () => {
  assert.deepEqual(questions.map((q) => q.q), EXPECTED_STATEMENTS);
  for (const q of questions) {
    assert.ok(q.q.length > 25, "statement of question " + q.id + " is truncated");
    assert.ok(!q.q.endsWith("..."), "statement of question " + q.id + " is truncated");
  }
});

test("every question carries the fields the page and the export need", () => {
  for (const q of questions) {
    assert.equal(typeof q.nav, "string", "nav of question " + q.id);
    assert.ok(q.nav.length > 5, "nav of question " + q.id);
    assert.equal(typeof q.answer, "string", "answer of question " + q.id);
    assert.ok(q.answer.trim().length > 200, "answer of question " + q.id + " is too short");
    assert.ok(q.catName, "catName of question " + q.id);
    if (q.code) {
      assert.ok(q.code.lang, "code lang of question " + q.id);
      assert.ok(q.code.body.trim().length > 20, "code body of question " + q.id);
    }
    if (q.flow) {
      assert.ok(q.flow.title, "flow title of question " + q.id);
      if (q.flow.kind === "table") {
        assert.ok(Array.isArray(q.flow.head), "flow head of question " + q.id);
        assert.ok(Array.isArray(q.flow.rows), "flow rows of question " + q.id);
      } else {
        assert.ok(Array.isArray(q.flow.items), "flow items of question " + q.id);
      }
    }
  }
});

test("the categories and their counts are the expected ones", () => {
  assert.deepEqual(cats.map((c) => c.id), Object.keys(EXPECTED_COUNTS));
  for (const c of cats) {
    const inCat = questions.filter((q) => q.cat === c.id);
    assert.equal(inCat.length, EXPECTED_COUNTS[c.id], "count of category " + c.id);
    for (const q of inCat) assert.equal(q.catName, c.name, "catName of question " + q.id);
  }
  const counted = questions.reduce((acc, q) => {
    acc[q.cat] = (acc[q.cat] || 0) + 1;
    return acc;
  }, {});
  assert.deepEqual(counted, EXPECTED_COUNTS);
  assert.equal(Object.values(counted).reduce((a, b) => a + b, 0), 21);
});

test("the AI answers keep the evaluation vocabulary", () => {
  const aiText = questions
    .filter((q) => q.cat === "ai")
    .map((q) => q.answer + " " + (q.flow ? q.flow.note || "" : ""))
    .join("\n");
  for (const term of AI_TERMS) {
    assert.ok(aiText.includes(term), "the AI answers no longer mention " + term);
  }
});

test("the content is in English", () => {
  const portuguese = /\b(voc[eê]|voc[eê]s|n[aã]o|n[oó]s|est[aá]|est[aã]o|j[aá]|tamb[eé]m|uma|para|com|mais|nossa|nosso|se[cç][aã]o|arquivo|p[aá]gina|resposta|pergunta)\b/i;
  for (const q of questions) {
    assert.ok(!portuguese.test(q.q), "statement of question " + q.id + " is not English");
    assert.ok(!portuguese.test(q.answer), "answer of question " + q.id + " is not English");
    assert.ok(!/[\u00e3\u00f5\u00e7]/.test(q.q + q.answer), "question " + q.id + " has Portuguese accents");
  }
});
